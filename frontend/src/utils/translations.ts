export function t(key: string, lang: string, params?: Record<string, string>): string {
  const langKey = (lang in translations ? lang : 'English') as LanguageCode;
  let str = translations[langKey]?.[key] || translations.English[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return str;
}
